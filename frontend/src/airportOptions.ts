const normalize = (value: string) => value.trim().toLowerCase()
  .replace(/(?:国际机场|机场|市)$/, '').replace(/\s+/g, ' ').trim()

export function matchingAirports(value: string) {
  const input = normalize(value)
  if (!input) return []
  return airportOptions.filter(({ code, name, aliases }) =>
    [code, name, name + '机场', name + '国际机场', ...aliases].some(alias => normalize(alias) === input),
  )
}

export function airportCode(value: string) {
  const code = value.trim().toUpperCase()
  return matchingAirports(value)[0]?.code ?? (/^[A-Z]{3}$/.test(code) ? code : '')
}
