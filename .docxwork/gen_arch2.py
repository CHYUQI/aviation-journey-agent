A("UI1 ..> B1 : 调用")
A("UI2 ..> B1 : 调用")
A("UI3 ..> B1 : 调用")
A("UI2 ..> B4 : 订阅实时快照")
A("UI3 ..> I3 : 用户点击后跳转")
A("B1 ..> B2 : 请求取数")
A("B1 ..> B3 : 请求决策")
A("B1 ..> B4 : 提交快照")
A("B2 ..> B4 : 观测结果")
A("B3 ..> B4 : 建议结果")
A("B2 ..> I1 : 使用")
A("B3 ..> I2 : 使用")
A("I1 -- X1")
A("I2 -- X2")
A("I3 -- X3")
A("")
A("' ==================== 与数据层、实体的关系 ====================")
A("B1 ..> E1 : 读取行程")
A("B1 ..> E4 : 读写位置与阶段")
A("B2 ..> E3 : 写入行程状态")
A("B4 ..> E0 : 保存与读取快照")
A("B4 -up- ISnap")
A("E0 ..> ISnap : 实现")
A("E1 \"1\" *-- \"1..*\" E2 : 包含航段")
A("E0 \"1\" *-- \"1\" E3 : 包含状态")
A("E0 \"1\" *-- \"1\" E4 : 包含进度")
A("")
A("' ==================== 体系结构约束 ====================")
A("note top of L1")
A("  只负责展示与上报，不计算风险、不推断旅客阶段")
