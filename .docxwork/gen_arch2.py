A("@startuml")
A("' 图2-1 系统体系结构图（分层结构视图）")
A("' 画法：分层包 + 构造型类（boundary / control / entity / interface）+ 层间依赖")
A("' 名称均为概念名，不对应代码中的包名与类名")
A("")
A('skinparam defaultFontName "Microsoft YaHei"')
A("skinparam defaultFontSize 15")
A("skinparam shadowing false")
A("skinparam classAttributeIconSize 0")
A("skinparam packageStyle rectangle")
A("skinparam nodesep 26")
A("skinparam ranksep 42")
A("skinparam ArrowColor #333333")
A("skinparam ArrowFontSize 12")
A("skinparam classBackgroundColor #FFFFFF")
A("skinparam classBorderColor #1F1F1F")
A("skinparam classFontColor #111111")
A("skinparam packageBorderColor #1F1F1F")
A("skinparam packageFontColor #111111")
A("")
A("title 图2-1 系统体系结构图")
A("")
A("' ==================== 用户界面层 ====================")
A('package "用户界面层" as L1 {')
A('  class "行程创建界面类" as UI1 <<boundary>> {')
A("    +录入航班与行李信息()")
A("    +提交行程()")
A("  }")
A('  class "行程状态界面类" as UI2 <<boundary>> {')
A("    +展示状态与时间轴()")
A("    +展示行动建议()")
A("  }")
A('  class "定位与阶段确认界面类" as UI3 <<boundary>> {')
A("    +上报当前位置()")
A("    +确认所处阶段()")
A("  }")
A("}")
A("")
A("' ==================== 业务逻辑层 ====================")
A('package "业务逻辑层" as L2 {')
A('  class "行程编排控制类" as B1 <<control>> {')
A("    -行程标识")
A("    +创建行程()")
A("    +更新位置或阶段()")
A("    +触发重算()")
A("  }")
A('  class "数据感知控制类" as B2 <<control>> {')
A("    +获取航班与机场数据()")
A("    +校验观测数据()")
A("    +评估数据质量()")
A("  }")
A('  class "行动决策控制类" as B3 <<control>> {')
A("    +分析阶段与风险()")
A("    +生成行动建议()")
A("    +执行风险下限()")
A("  }")
A('  class "快照与推送控制类" as B4 <<control>> {')
A("    +保存完整快照()")
A("    +广播完整快照()")
A("  }")
A("}")
A("")
A("' 业务逻辑层右侧：快照实体与其读写接口（对应参考图中的实体类 + 接口圆）")
A('class "行程快照实体类" as E0 <<entity>> {')
A("  -分析状态")
A("  -生成时间")
A("  -数据质量")
A("}")
A('interface "快照读写接口" as ISnap')
A("")
A("' ==================== 数据层 ====================")
A('package "数据层" as L3 {')
A('  class "行程实体类" as E1 <<entity>> {')
A("    -行程标识")
A("    -是否托运行李")
A("  }")
A('  class "航段实体类" as E2 <<entity>> {')
A("    -航班号")
A("    -出行日期")
A("    -出发机场")
A("    -到达机场")
A("  }")
A('  class "行程状态实体类" as E3 <<entity>> {')
A("    -航班状态")
A("    -时间轴节点")
A("    -预计路程时长")
A("    -数据质量")
A("  }")
A('  class "位置进度实体类" as E4 <<entity>> {')
A("    -经度")
A("    -纬度")
A("    -手动确认阶段")
A("  }")
A("}")
A("")
A("' ==================== 设备接口层 ====================")
A('package "设备接口层" as L4 {')
A('  interface "聚合数据源接口" as I1')
A('  interface "大模型接口" as I2')
A('  interface "地图导航接口" as I3')
A("}")
A("")
A("' ==================== 外部系统 ====================")
A('class "航班与机场数据来源" as X1 <<external>>')
A('class "大模型服务" as X2 <<external>>')
A('class "地图导航应用或网页" as X3 <<external>>')
A("")
