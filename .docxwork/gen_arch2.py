A("note bottom of L3")
A("  课程版为进程内存储，进程重启数据丢失，不支持多实例共享")
A("end note")
A("note bottom of L4")
A("  外部数据只经接口层进入系统；未配置大模型时系统仍可运行")
A("end note")
A("")
A("@enduml")
